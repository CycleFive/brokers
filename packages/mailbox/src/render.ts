import type { Copy, Manifest, MailSource, Template } from "./manifest.ts";

type Obj = Record<string, unknown>;

/** The wrangler config of one broker copy. */
export function renderBroker(copy: Copy, template: Template, kvId: string): Record<string, unknown> {
  const config = structuredClone(template.config);
  config.name = copy.worker;
  config.vars = structuredClone(copy.vars);
  const [kv] = config.kv_namespaces as Obj[];
  config.kv_namespaces = [{ binding: kv.binding, id: kvId }];
  if (copy.customDomain) {
    config.routes = [{ pattern: copy.host, custom_domain: true }];
    config.workers_dev = false;
    config.preview_urls = false;
  }
  return config;
}

/** mailroom-core's wrangler config: `example` is mailroom's parsed wrangler.example.jsonc. Throws Error when no mailbox has "mail". */
export function renderMailroom(manifest: Manifest, copies: Copy[], example: Record<string, unknown>): Record<string, unknown> {
  const config = structuredClone(example);
  delete config.$schema;

  const copyOf = (mailbox: string, broker: string): Copy => {
    const copy = copies.find((c) => c.mailbox === mailbox && c.broker === broker);
    if (!copy) throw new Error(`mailboxes.${mailbox}: no copy of broker "${broker}"`);
    return copy;
  };

  const used = new Set<Copy>();
  const agents: Obj = {};
  for (const [mailbox, mb] of Object.entries(manifest.mailboxes)) {
    if (!mb.mail) continue;
    const signin = copyOf(mailbox, mb.mail.signin);
    const sources = mb.mail.sources.map((s) => ({ source: s, copy: copyOf(mailbox, s.broker) }));
    for (const copy of [signin, ...sources.map((s) => s.copy)]) used.add(copy);
    agents[mailbox] = {
      signin: signin.binding,
      sources: sources.map(({ source, copy }): MailSource => ({ ...structuredClone(source), broker: copy.binding })),
    };
  }
  if (Object.keys(agents).length === 0) throw new Error("no mailbox has a \"mail\" entry, so there is nothing to render for the mailroom");

  config.services = copies.filter((c) => used.has(c)).map((c) => ({ binding: c.binding, service: c.worker, entrypoint: "Feed" }));
  const vars = (config.vars ?? {}) as Obj;
  vars.MAILROOM = manifest.mailroom?.retain_days === undefined ? { agents } : { retain_days: manifest.mailroom.retain_days, agents };
  config.vars = vars;
  return config;
}

/** Text of a generated file: one header comment line, then JSON with two-space indent and a final newline. */
export function serialize(config: Record<string, unknown>, manifestPath: string): string {
  return `// Generated by \`npm run mailbox\` from ${manifestPath}. Do not edit: change the manifest and run it again.\n${JSON.stringify(config, null, 2)}\n`;
}
